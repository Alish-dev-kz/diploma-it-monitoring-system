-- ITMon: Компьютерлік техниканы орталықтандырылған мониторингтеу жүйесінің деректер қоры
-- DBMS: SQLite 3.35+ (window functions, RETURNING). Run:
--   sqlite3 itmon_design.db < db/schema.sql
--   sqlite3 itmon_design.db < db/queries.sql
-- Schema is in 3NF: every non-key attribute depends only on the key of its table.

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS reports;
DROP TABLE IF EXISTS audit_log;
DROP TABLE IF EXISTS commands;
DROP TABLE IF EXISTS command_types;
DROP TABLE IF EXISTS incidents;
DROP TABLE IF EXISTS alerts;
DROP TABLE IF EXISTS thresholds;
DROP TABLE IF EXISTS metrics;
DROP TABLE IF EXISTS metric_types;
DROP TABLE IF EXISTS agent_tokens;
DROP TABLE IF EXISTS devices;
DROP TABLE IF EXISTS device_groups;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS roles;

-- 1. Roles (RBAC)
CREATE TABLE roles (
    id          INTEGER PRIMARY KEY,
    code        TEXT NOT NULL UNIQUE,
    name        TEXT NOT NULL,
    can_execute INTEGER NOT NULL DEFAULT 0 CHECK (can_execute IN (0, 1))  -- may send remote commands
);

-- 2. Users of the web panel
CREATE TABLE users (
    id            INTEGER PRIMARY KEY,
    full_name     TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role_id       INTEGER NOT NULL REFERENCES roles(id),
    is_active     INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at    TEXT NOT NULL DEFAULT (datetime('now'))
);

-- 3. Device groups (department / classroom)
CREATE TABLE device_groups (
    id       INTEGER PRIMARY KEY,
    name     TEXT NOT NULL UNIQUE,
    location TEXT NOT NULL
);

-- 4. Monitored computers
CREATE TABLE devices (
    id            INTEGER PRIMARY KEY,
    agent_uid     TEXT NOT NULL UNIQUE,              -- id generated by the agent
    hostname      TEXT NOT NULL,
    os            TEXT NOT NULL,
    ip_address    TEXT,
    group_id      INTEGER REFERENCES device_groups(id) ON DELETE SET NULL,
    registered_at TEXT NOT NULL,
    last_seen     TEXT
);

-- 5. Per-agent tokens (only hash is stored)
CREATE TABLE agent_tokens (
    id         INTEGER PRIMARY KEY,
    device_id  INTEGER NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL,
    revoked_at TEXT
);

-- 6. Metric dictionary
CREATE TABLE metric_types (
    id   INTEGER PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    unit TEXT NOT NULL
);

-- 7. Time series of measurements ("long" format: one row = one value)
CREATE TABLE metrics (
    id             INTEGER PRIMARY KEY,
    device_id      INTEGER NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    metric_type_id INTEGER NOT NULL REFERENCES metric_types(id),
    value          REAL NOT NULL,
    measured_at    TEXT NOT NULL
);
CREATE INDEX ix_metrics_device_type_time ON metrics(device_id, metric_type_id, measured_at);

-- 8. Thresholds: global (group_id IS NULL) or per group
CREATE TABLE thresholds (
    id                INTEGER PRIMARY KEY,
    metric_type_id    INTEGER NOT NULL REFERENCES metric_types(id),
    group_id          INTEGER REFERENCES device_groups(id) ON DELETE CASCADE,
    warn_value        REAL NOT NULL,
    crit_value        REAL NOT NULL,
    consecutive_count INTEGER NOT NULL DEFAULT 3 CHECK (consecutive_count >= 1),
    CHECK (warn_value < crit_value),
    UNIQUE (metric_type_id, group_id)
);

-- 9. Alerts produced by diagnostics
CREATE TABLE alerts (
    id              INTEGER PRIMARY KEY,
    device_id       INTEGER NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    metric_type_id  INTEGER REFERENCES metric_types(id),   -- NULL for "agent offline"
    level           TEXT NOT NULL CHECK (level IN ('warn', 'crit', 'offline')),
    message         TEXT NOT NULL,
    created_at      TEXT NOT NULL,
    acknowledged_by INTEGER REFERENCES users(id),
    acknowledged_at TEXT,
    status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'acknowledged', 'resolved'))
);

-- 10. Incidents (work items for engineers)
CREATE TABLE incidents (
    id          INTEGER PRIMARY KEY,
    alert_id    INTEGER UNIQUE REFERENCES alerts(id) ON DELETE SET NULL,
    title       TEXT NOT NULL,
    assigned_to INTEGER REFERENCES users(id),
    status      TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'in_progress', 'closed')),
    created_at  TEXT NOT NULL,
    closed_at   TEXT
);

-- 11. Whitelist of remote commands
CREATE TABLE command_types (
    id             INTEGER PRIMARY KEY,
    code           TEXT NOT NULL UNIQUE,
    name           TEXT NOT NULL,
    timeout_sec    INTEGER NOT NULL DEFAULT 60  CHECK (timeout_sec > 0),
    ttl_sec        INTEGER NOT NULL DEFAULT 300 CHECK (ttl_sec > 0),
    max_attempts   INTEGER NOT NULL DEFAULT 3   CHECK (max_attempts >= 1),
    is_destructive INTEGER NOT NULL DEFAULT 0   CHECK (is_destructive IN (0, 1))
);

-- 12. Command queue (the "difficult part": TTL + retries for offline agents)
CREATE TABLE commands (
    id              INTEGER PRIMARY KEY,
    device_id       INTEGER NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    command_type_id INTEGER NOT NULL REFERENCES command_types(id),
    requested_by    INTEGER NOT NULL REFERENCES users(id),
    status          TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'running', 'done', 'failed', 'expired')),
    attempts        INTEGER NOT NULL DEFAULT 0,
    created_at      TEXT NOT NULL,
    expires_at      TEXT NOT NULL,
    started_at      TEXT,
    finished_at     TEXT,
    result          TEXT
);
CREATE INDEX ix_commands_queue ON commands(device_id, status);

-- 13. Audit log (who, when, what)
CREATE TABLE audit_log (
    id          INTEGER PRIMARY KEY,
    user_id     INTEGER REFERENCES users(id),
    action      TEXT NOT NULL,
    entity      TEXT NOT NULL,
    entity_id   INTEGER,
    details     TEXT,
    created_at  TEXT NOT NULL
);

-- 14. Generated reports
CREATE TABLE reports (
    id          INTEGER PRIMARY KEY,
    created_by  INTEGER NOT NULL REFERENCES users(id),
    group_id    INTEGER REFERENCES device_groups(id),
    period_from TEXT NOT NULL,
    period_to   TEXT NOT NULL,
    format      TEXT NOT NULL CHECK (format IN ('pdf', 'xlsx')),
    created_at  TEXT NOT NULL,
    CHECK (period_from <= period_to)
);

